"""``devtools schema new`` -- generate a typed declaration and its adapter scaffolding.

The scaffold is domain-pluggable, not a universal code generator. Each
:class:`ScaffoldFamily` owns its own templates and its own reuse question; the
shared half is the unification interview (the five
:class:`~polylogue.declarations.models.CompatibilityKey` dimensions), the
reuse/justification refusal, and the write protocol (plan -> collision check ->
atomic apply with rollback).

Every generated bundle contains:

* ``declaration.py`` -- a compiling module that builds a real ``DeclarationSpec``
* ``adapter.py``     -- an implementation stub bound to the production adapter
* ``test_route_contract.py`` -- a contract skeleton that pushes the generated
  minimal-valid and invalid example arguments through the *production* adapter
* ``PLAN.md``        -- the exact repository paths and generated-surface
  commands needed to land the scaffold

Generation is deterministic: the same answers produce byte-identical output.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from devtools import repo_root as _get_root
from polylogue.declarations import CompatibilityKey, DeclarationRegistryProtocol

ROOT = _get_root()
DEFAULT_OUTPUT_ROOT = Path(".cache/scaffold")

COMPATIBILITY_DIMENSIONS: tuple[str, ...] = (
    "identity",
    "lifecycle",
    "authority",
    "access_result_shape",
    "durability",
)

#: Durability answers that assert a *new* durable object or registry. Creating
#: one without a justification is refused: durable state is the one decision a
#: scaffold must never make silently.
DURABLE_ANSWERS: frozenset[str] = frozenset({"durable", "durable-new-object", "new-registry"})


class ScaffoldError(RuntimeError):
    """An actionable refusal: what is wrong, and which flag repairs it."""


@dataclass(frozen=True, slots=True)
class ScaffoldFile:
    """One planned output file."""

    relative_path: str
    content: str


@dataclass(frozen=True, slots=True)
class ScaffoldAnswers:
    """The recorded unification interview for one scaffold run."""

    family: str
    name: str
    compatibility: CompatibilityKey
    reuse_family: str | None
    justification: str

    def as_dict(self) -> dict[str, object]:
        return {
            "family": self.family,
            "name": self.name,
            "compatibility": {
                dimension: getattr(self.compatibility, dimension) for dimension in COMPATIBILITY_DIMENSIONS
            },
            "reuse_family": self.reuse_family,
            "justification": self.justification,
        }


@dataclass(frozen=True, slots=True)
class ScaffoldPlan:
    """A complete, inspectable generation plan."""

    answers: ScaffoldAnswers
    output_root: str
    files: tuple[ScaffoldFile, ...]
    instructions: tuple[str, ...]

    def as_dict(self) -> dict[str, object]:
        return {
            "answers": self.answers.as_dict(),
            "output_root": self.output_root,
            "files": [item.relative_path for item in self.files],
            "instructions": list(self.instructions),
        }


@dataclass(frozen=True, slots=True)
class ScaffoldFamily:
    """One domain's scaffold templates and registry ownership."""

    name: str
    description: str
    #: Callable returning the live registry whose families may be reused.
    registry: Callable[[], DeclarationRegistryProtocol]
    render: Callable[[ScaffoldAnswers, str], tuple[ScaffoldFile, ...]]
    instructions: tuple[str, ...]
    owner_path: str


def _module_name(name: str) -> str:
    return name.replace("-", "_")


def _mcp_registry() -> DeclarationRegistryProtocol:
    from polylogue.mcp.declarations.registry import MCP_KERNEL_REGISTRY

    return MCP_KERNEL_REGISTRY


def _daemon_registry() -> DeclarationRegistryProtocol:
    from polylogue.daemon.route_contracts import DAEMON_ROUTE_REGISTRY

    return DAEMON_ROUTE_REGISTRY


def _compatibility_literal(compatibility: CompatibilityKey) -> str:
    fields = ",\n".join(
        f"        {dimension}={getattr(compatibility, dimension)!r}" for dimension in COMPATIBILITY_DIMENSIONS
    )
    return f"CompatibilityKey(\n{fields},\n    )"


