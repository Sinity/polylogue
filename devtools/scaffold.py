FAMILY_BY_NAME: dict[str, ScaffoldFamily] = {family.name: family for family in FAMILIES}


def compatible_family(registry: DeclarationRegistryProtocol, compatibility: CompatibilityKey) -> str | None:
    """Return an existing family whose compatibility key matches exactly."""

    for family in registry.families():
        if not family.compatibility.differences(compatibility):
            return family.family_id
    return None


def build_plan(
    family_name: str,
    name: str,
    *,
    compatibility: CompatibilityKey,
    reuse_family: str | None = None,
    justification: str = "",
    output_root: Path = DEFAULT_OUTPUT_ROOT,
) -> ScaffoldPlan:
    """Answer the unification questions, refuse or reuse, and plan the files."""

    family = FAMILY_BY_NAME.get(family_name)
    if family is None:
        raise ScaffoldError(
            f"unknown scaffold family {family_name!r}; declared families: {', '.join(sorted(FAMILY_BY_NAME))}"
        )
    missing = [dimension for dimension in COMPATIBILITY_DIMENSIONS if not getattr(compatibility, dimension)]
    if missing:
        raise ScaffoldError(
            "the unification interview is incomplete; answer "
            + ", ".join(f"--{dimension.replace('_', '-')}" for dimension in missing)
        )

    registry = family.registry()
    existing = compatible_family(registry, compatibility)
    if reuse_family is not None:
        known = {item.family_id for item in registry.families()}
        if reuse_family not in known:
            raise ScaffoldError(
                f"--reuse-family {reuse_family!r} is not a declared family in {family.owner_path}; "
                f"declared families: {', '.join(sorted(known))}"
            )
        member = next(item for item in registry.families() if item.family_id == reuse_family)
        differences = member.compatibility.differences(compatibility)
        if differences:
            detail = ", ".join(f"{field}: {left!r} != {right!r}" for field, left, right in differences)
            raise ScaffoldError(
                f"--reuse-family {reuse_family!r} is incompatible with the answered interview ({detail}); "
                "either match the family or justify a new one with --justification"
            )
    elif existing is not None and not justification:
        raise ScaffoldError(
            f"family {existing!r} already declares this exact compatibility key; reuse it with "
            f"--reuse-family {existing} or record why a new declaration is needed with --justification"
        )
    elif compatibility.durability in DURABLE_ANSWERS and not justification:
        raise ScaffoldError(
            f"durability {compatibility.durability!r} asserts a new durable object or registry; "
            "record why with --justification before generating it"
        )

    answers = ScaffoldAnswers(
        family=family.name,
        name=name,
        compatibility=compatibility,
        reuse_family=reuse_family,
        justification=justification,
    )
    target = output_root / family.name / _module_name(name)
    files = list(family.render(answers, str(target)))
    plan_lines = [
        f"# Landing plan: {family.name} / {name}",
        "",
        "## Recorded unification answers",
        "",
        "```json",
        json.dumps(answers.as_dict(), indent=2, sort_keys=True),
        "```",
        "",
        "## Generated outputs",
        "",
        *(f"- `{target}/{item.relative_path}`" for item in files),
        "",
        "## Steps",
        "",
        *(f"{index}. {step}" for index, step in enumerate(family.instructions, start=1)),
        "",
    ]
    files.append(ScaffoldFile("PLAN.md", "\n".join(plan_lines)))
    return ScaffoldPlan(
        answers=answers,
        output_root=str(target),
        files=tuple(files),
        instructions=family.instructions,
    )


def apply_plan(plan: ScaffoldPlan, *, root: Path = ROOT) -> tuple[Path, ...]:
    """Write a planned bundle, refusing collisions and rolling back partials.

    A collision is refused before the first byte is written. If any later write
    fails, every file this call created is removed, so a failed scaffold never
    leaves a half-written bundle behind.
    """

    target = root / plan.output_root
    collisions = [item.relative_path for item in plan.files if (target / item.relative_path).exists()]
    if collisions:
        raise ScaffoldError(
            f"refusing to overwrite existing scaffold output in {target}: {', '.join(sorted(collisions))}"
        )
    written: list[Path] = []
    try:
        target.mkdir(parents=True, exist_ok=True)
        for item in plan.files:
            path = target / item.relative_path
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(item.content, encoding="utf-8")
            written.append(path)
    except OSError:
        for path in written:
            path.unlink(missing_ok=True)
        raise
    return tuple(written)


#: Which registry in ``devtools.verify_declaration_bindings`` owns each family.
_REGISTRY_NAME_BY_FAMILY: dict[str, str] = {"mcp-tool": "mcp", "daemon-route": "daemon-route"}


def validate_owner_registry(family_name: str, *, root: Path = ROOT) -> tuple[str, ...]:
    """Return actionable diagnostics for the family's live owning registry.

    Delegates to the ``declaration-bindings`` gate so the scaffold and the gate
    cannot disagree about what a complete registration means.
    """

    from devtools.verify_declaration_bindings import run as run_bindings

    family = FAMILY_BY_NAME.get(family_name)
    if family is None:
        raise ScaffoldError(f"unknown scaffold family {family_name!r}")
    return run_bindings(root=root)[_REGISTRY_NAME_BY_FAMILY[family.name]]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="devtools schema new",
        description="Generate a typed declaration, adapter stub, contract skeleton, and landing plan.",
    )
    parser.add_argument("family", nargs="?", help="Scaffold family (omit with --list to see the declared families).")
    parser.add_argument("name", nargs="?", help="Public name of the new declaration.")
    parser.add_argument("--list", action="store_true", help="List the declared scaffold families and exit.")
    for dimension in COMPATIBILITY_DIMENSIONS:
        parser.add_argument(
            f"--{dimension.replace('_', '-')}",
            default="",
            help=f"Unification answer for the {dimension} compatibility dimension.",
        )
    parser.add_argument("--reuse-family", default=None, help="Join this existing declaration family.")
    parser.add_argument("--justification", default="", help="Why a new family or durable object is needed.")
    parser.add_argument("--dry-run", action="store_true", help="Print the plan without writing any file.")
    parser.add_argument("--json", action="store_true", help="Emit the plan as JSON.")
    parser.add_argument(
        "--validate",
        action="store_true",
        help="Report actionable diagnostics for the family's live owning registry and exit.",
    )
    parser.add_argument("--output-root", default=str(DEFAULT_OUTPUT_ROOT), help="Directory that receives the bundle.")
    args = parser.parse_args(argv)

    if args.list or args.family is None:
        for family in FAMILIES:
            print(f"{family.name}: {family.description}")
        return 0 if args.list or args.family is None else 1

    try:
        if args.validate:
            diagnostics = validate_owner_registry(args.family)
            for line in diagnostics:
                print(line, file=sys.stderr)
            if diagnostics:
                return 1
            print(f"devtools schema new: {args.family}: owning registry is complete")
            return 0

        if args.name is None:
            raise ScaffoldError("a public name is required: devtools schema new <family> <name>")
        plan = build_plan(
            args.family,
            args.name,
            compatibility=CompatibilityKey(
                identity=args.identity,
                lifecycle=args.lifecycle,
                authority=args.authority,
                access_result_shape=args.access_result_shape,
                durability=args.durability,
            ),
            reuse_family=args.reuse_family,
            justification=args.justification,
            output_root=Path(args.output_root),
        )
    except ScaffoldError as exc:
        print(f"devtools schema new: {exc}", file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(plan.as_dict(), indent=2, sort_keys=True))
    else:
        print(f"devtools schema new: plan for {plan.answers.family}/{plan.answers.name} in {plan.output_root}")
        for item in plan.files:
            print(f"devtools schema new:   {plan.output_root}/{item.relative_path}")
        for index, step in enumerate(plan.instructions, start=1):
            print(f"devtools schema new:   {index}. {step}")
    if args.dry_run:
        print("devtools schema new: dry run; nothing written")
        return 0
    try:
        written = apply_plan(plan)
    except ScaffoldError as exc:
        print(f"devtools schema new: {exc}", file=sys.stderr)
        return 1
    print(f"devtools schema new: wrote {len(written)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
