//! MCP over stdio, as a proxy to the daemon. The commands the table offers
//! over MCP are grouped by access; a call names the operation (the
//! command) and carries its arguments, which are checked against the table
//! and sent as the same request the CLI sends. Answers are the daemon's
//! structured answers; reads use the shared Markdown renderer, and context
//! (briefs, takeovers, recalls) is answered with its text and
//! recorded as a delivery from `mcp`. Refusals are tool errors.

mod completion;

use crate::commands::{COMMANDS, Command, Tool, ToolAccess};
use crate::protocol::line::{LineAnswer, StepAnswer, StepOutcome};
use command_surface::Answer;
use polylogue_store::Archive;
use serde_json::{Map, Value, json};
use std::io::{self, BufRead, Write};

/// The commands offered as tool operations.
pub fn tool_commands() -> impl Iterator<Item = &'static Command> {
    COMMANDS
        .iter()
        .filter(|c| c.tool.is_some() && c.registration().is_some())
}

/// The operations of one tool.
pub fn operations(tool: Tool) -> impl Iterator<Item = &'static Command> {
    tool_commands().filter(move |c| c.tool == Some(tool))
}

/// The tool list, generated by the shared declarations from the rows.
pub fn tools() -> Vec<Value> {
    let declared = crate::commands::declarations().mcp_tools();
    let mut tools = declared.clone();
    for tool in &mut tools {
        let name = tool["name"].as_str().unwrap_or_default().to_owned();
        let Some(own) = Tool::named(&name) else {
            continue;
        };
        let access = own.access();
        if matches!(own, Tool::Write | Tool::Act) {
            for smaller in &declared {
                let smaller_name = smaller["name"].as_str().unwrap_or_default();
                if Tool::named(smaller_name)
                    .is_some_and(|family| family.access() <= access && family != own)
                {
                    merge_tool(tool, smaller);
                }
            }
        }
        if let Some(required) = tool["inputSchema"]["required"].as_array_mut() {
            required.retain(|field| field != "operation");
        }
        tool["annotations"] = match access {
            ToolAccess::Read => json!({"readOnlyHint":true,"openWorldHint":false}),
            ToolAccess::Write => {
                json!({"readOnlyHint":false,"idempotentHint":true,"openWorldHint":false})
            }
            ToolAccess::Act => {
                json!({"readOnlyHint":false,"destructiveHint":false,"openWorldHint":true})
            }
        };
    }
    // Listing and showing a setting are reads even though its home family writes.
    if let Some(set) = declared.iter().find(|tool| {
        tool["inputSchema"]["properties"]["operation"]["enum"]
            .as_array()
            .is_some_and(|names| names.contains(&json!("set")))
    }) {
        let mut listing = set.clone();
        listing["inputSchema"]["properties"]["operation"]["enum"] = json!(["set"]);
        listing["inputSchema"]["properties"]["arguments"]["properties"] =
            json!({"key":{"type":"string"},"machine":{"type":"string"}});
        if let Some(read) = tools
            .iter_mut()
            .find(|tool| tool["name"] == Tool::Read.name())
        {
            merge_tool(read, &listing);
        }
    }
    tools
}

fn merge_tool(tool: &mut Value, smaller: &Value) {
    let names = smaller["inputSchema"]["properties"]["operation"]["enum"]
        .as_array()
        .expect("operation names");
    let offered = tool["inputSchema"]["properties"]["operation"]["enum"]
        .as_array_mut()
        .expect("operation names");
    for name in names {
        if !offered.contains(name) {
            offered.push(name.clone());
        }
    }
    let fields = smaller["inputSchema"]["properties"]["arguments"]["properties"]
        .as_object()
        .expect("argument properties");
    let properties = tool["inputSchema"]["properties"]["arguments"]["properties"]
        .as_object_mut()
        .expect("argument properties");
    for (name, field) in fields {
        match properties.get_mut(name) {
            Some(existing) if existing != field => {
                if let Some(choices) = existing.get_mut("anyOf").and_then(Value::as_array_mut) {
                    if !choices.contains(field) {
                        choices.push(field.clone());
                    }
                } else {
                    *existing = json!({"anyOf":[existing.clone(), field]});
                }
            }
            Some(_) => {}
            None => {
                properties.insert(name.clone(), field.clone());
            }
        }
    }
}

/// One text form for a failure: its code, message and runnable correction,
/// so an agent can retry with it as given.
fn error_text(failure: &command_surface::Failure) -> String {
    let code = failure.code.clone().unwrap_or_else(|| {
        serde_json::to_value(failure.kind)
            .ok()
            .and_then(|kind| kind.as_str().map(str::to_owned))
            .unwrap_or_default()
    });
    let mut text = format!("error ({code}): {}", failure.message);
    if let Some(suggestion) = crate::protocol::suggestion_text(failure).as_deref() {
        text.push_str(&format!("\ntry: {suggestion}"));
    }
    for candidate in failure.candidates() {
        text.push_str(&format!("\n  {candidate}"));
    }
    polylogue_render::terminal::escape(&text)
}

fn bad_request(message: &str) -> String {
    polylogue_render::terminal::escape(&format!("error (bad_request): {message}"))
}

/// The text content beside the structured answer: shared Markdown for reads,
/// prepared text for context, and JSON for other values. A failure names its notes.
fn format_answer(
    command: &Command,
    answer: Result<&Answer<Value>, &std::io::Error>,
) -> Result<String, String> {
    let answer = answer.map_err(|e| {
        polylogue_render::terminal::escape(&format!(
            "error (daemon_required): no Polylogue daemon answered ({e}); start it with `polylogue daemon`"
        ))
    })?;
    let notes = crate::protocol::notes(answer)
        .map(|note| format!("\nnote: {}", polylogue_render::terminal::escape(note)))
        .collect::<String>();
    match answer {
        command_surface::Answer {
            outcome: command_surface::Outcome::Error(error),
            ..
        } => Err(format!("{}{notes}", error_text(error))),
        answer => {
            if command.name == "rows" {
                let line: LineAnswer =
                    serde_json::from_value(answer.value().expect("successful rows answer").clone())
                        .map_err(|error| bad_request(&error.to_string()))?;
                return rows_text(&line).map(|text| format!("{text}{notes}"));
            }
            let value = answer.value().expect("a non-error answer has a value");
            Ok(polylogue_render::terminal::json(value, true))
        }
    }
}

fn rows_text(line: &LineAnswer) -> Result<String, String> {
    let LineAnswer::Steps(steps) = line else {
        return Ok(crate::cli::print::line(
            line,
            command_surface::TextStyle::Plain,
        ));
    };
    let mut text = String::new();
    for step in &steps.steps {
        let printed = match &step.outcome {
            StepOutcome::Done { reply, undo } => {
                let mut printed = match reply {
                    StepAnswer::Read(_) => {
                        let line = LineAnswer::Steps(crate::protocol::line::StepsAnswer {
                            resolved: None,
                            steps: vec![step.clone()],
                        });
                        let answer =
                            Answer::ok(serde_json::to_value(line).expect("read step serializes"));
                        crate::commands::declarations()
                            .render_text("rows", &answer, command_surface::TextStyle::Plain)
                            .map_err(|failure| error_text(&failure))?
                    }
                    other => crate::cli::print::step_reply(
                        other,
                        &step.verb,
                        command_surface::TextStyle::Plain,
                    ),
                };
                for line in undo {
                    printed.push_str(&format!(
                        "\nundo: {}",
                        polylogue_render::terminal::escape(line)
                    ));
                }
                printed
            }
            StepOutcome::Failed { error } => error_text(error),
            StepOutcome::NotRun => format!("{} not run", step.verb),
            StepOutcome::WouldDo { would, refusal } => match refusal {
                Some(error) => format!(
                    "{}\n{}",
                    polylogue_render::terminal::escape(would),
                    error_text(error)
                ),
                None => polylogue_render::terminal::escape(would),
            },
        };
        if !text.is_empty() {
            text.push('\n');
        }
        text.push_str(&printed);
    }
    Ok(text)
}

fn arguments_for(request: &command_surface::RunnableRequest) -> Value {
    crate::commands::declarations()
        .mcp_call(request)
        .expect("tool request")["arguments"]
        .clone()
}

fn refusal(
    failure: command_surface::Failure,
    next: Option<command_surface::Next>,
) -> (String, Value, bool) {
    let text = error_text(&failure);
    let mut answer = Answer::<Value>::error(failure);
    answer.envelope.next.extend(next);
    (
        text,
        serde_json::to_value(answer).expect("failure serializes"),
        true,
    )
}

/// A refusal that carries the corrected call: `call` as the arguments of
/// `tool`, in the text and as the one `next` request.
fn refusal_with_call(
    failure: command_surface::Failure,
    tool: Tool,
    call: &Value,
    request: command_surface::RunnableRequest,
) -> (String, Value, bool) {
    let correction = format!("{} {call}", tool.name());
    let mut result = refusal(
        failure,
        Some(command_surface::Next {
            label: correction.clone(),
            request,
        }),
    );
    result.0.push_str(&format!("\nnext: {correction}"));
    result
}

/// A `tools/call`: the tool's operation named by the call, run with its
/// arguments.
fn call_with_limit(
    archive: &Archive,
    name: &str,
    arguments: Map<String, Value>,
    deadline_ms: Option<i64>,
    cancelled: &tokio_util::sync::CancellationToken,
    tool_call_id: Option<String>,
) -> Result<(String, Value, bool), String> {
    let Some(tool) = Tool::named(name) else {
        return Err(bad_request(&format!("unknown MCP tool {name}")));
    };
    let operation = match arguments.get("operation") {
        None => "rows",
        Some(value) => value
            .as_str()
            .ok_or_else(|| bad_request("operation must be text"))?,
    };
    let Some(command) =
        crate::commands::command(operation).filter(|command| command.tool.is_some())
    else {
        return Err(bad_request(&format!("unknown operation {operation}")));
    };
    let home = command.tool.expect("tool operation");
    let caller = crate::client::this_process();
    let author = command_surface::author_of(&caller, command_surface::Via::Mcp, None).author;
    let mut arguments = Value::Object(arguments);
    arguments["operation"] = json!(command.name);
    let request = crate::commands::declarations()
        .parse_mcp_call_as(home.name(), arguments, &author)
        .map_err(|failure| error_text(&failure))?;
    if request.request_id.is_empty() {
        return Err(bad_request("request_id must not be empty"));
    }
    if !request.arguments.is_object() {
        return Err(bad_request("arguments must be an object"));
    }
    for field in ["cursor", "request_id"] {
        if request.arguments.get(field).is_some() {
            return Err(bad_request(&format!(
                "{field} goes beside arguments, not inside them"
            )));
        }
    }
    let access = match command
        .registration()
        .expect("tool handler")
        .tool_access(&request.arguments, command)
    {
        Ok(access) => access,
        Err(failure) => return Ok(refusal(failure.error, None)),
    };
    let setting_read = command.name == "set" && access == ToolAccess::Read;
    let needed = if setting_read {
        access
    } else {
        home.access().max(access)
    };
    if needed > tool.access() {
        let next_tool = Tool::with_access(needed);
        let failure = crate::protocol::failure(
            polylogue_model::Code::BadRequest,
            format!(
                "{} with these arguments needs {}",
                command.name,
                next_tool.name()
            ),
        );
        let mut next = arguments_for(&request);
        next["operation"] = json!(command.name);
        return Ok(refusal_with_call(failure, next_tool, &next, request));
    }
    run(archive, request, deadline_ms, cancelled, tool_call_id)
}

/// Runs one operation as the typed request the call names.
fn run(
    archive: &Archive,
    request: command_surface::RunnableRequest,
    deadline_ms: Option<i64>,
    cancelled: &tokio_util::sync::CancellationToken,
    tool_call_id: Option<String>,
) -> Result<(String, Value, bool), String> {
    let command = crate::commands::command(&request.operation)
        .ok_or_else(|| bad_request(&format!("unknown operation {}", request.operation)))?;
    // The row's typed arguments are checked here, as the daemon checks them,
    // so a malformed call is refused without a daemon.
    if let Some(registration) = command.registration() {
        let policy = match registration.admit(
            &request.arguments,
            command,
            &crate::commands::Caller {
                surface: crate::commands::Surface::Mcp,
                cwd: None,
            },
        ) {
            Ok(policy) => policy,
            Err(failure) => return Ok(refusal(failure.error, None)),
        };
        if policy.streaming {
            let mut next = request.clone();
            if command.name == "rows" {
                if let Some(steps) = next.arguments["steps"].as_array_mut() {
                    for step in steps {
                        if step["verb"] == "read" {
                            step["follow"] = json!(false);
                            step["delivery"] = json!("page");
                        }
                    }
                }
            } else {
                next.arguments["delivery"] = json!("page");
            }
            return Ok(refusal_with_call(
                crate::protocol::failure(
                    polylogue_model::Code::BadRequest,
                    "a model cannot hold a stream; read again to continue",
                ),
                Tool::Read,
                &arguments_for(&next),
                next,
            ));
        }
    }
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|e| e.to_string())?;
    let mut caller = crate::client::this_process();
    if tool_call_id.is_some() {
        caller.tool_call_id = tool_call_id;
    }
    let mut answer = runtime.block_on(crate::client::call_ready_as_bounded(
        archive,
        &request,
        cancelled,
        caller,
        deadline_ms,
    ));
    // The daemon's refusal carries the same line with `all` set; MCP offers
    // it as the next call.
    let all = answer
        .as_ref()
        .ok()
        .and_then(|answer| answer.failure())
        .filter(|failure| failure.code.as_deref() == Some("needs_all"))
        .and_then(|failure| match failure.suggestion() {
            Some(command_surface::Suggestion::Request(next)) => Some(next.clone()),
            _ => None,
        });
    if let (Ok(answer), Some(next)) = (&mut answer, all) {
        answer.envelope.next.push(command_surface::Next {
            label: "act on all matching rows".into(),
            request: next,
        });
    }
    let structured = match &answer {
        Ok(answer) => serde_json::to_value(answer).expect("answer serializes"),
        Err(error) => serde_json::to_value(command_surface::Answer::<Value>::error(
            crate::protocol::failure(polylogue_model::Code::NotRunning, error.to_string()),
        ))
        .expect("failure serializes"),
    };
    let failed = answer.as_ref().is_ok_and(|answer| command.name == "rows" && answer.value().is_some_and(|value| {
        serde_json::from_value::<LineAnswer>(value.clone()).is_ok_and(|line| matches!(line,
            LineAnswer::Steps(steps) if steps.steps.iter().any(|step| matches!(step.outcome, StepOutcome::Failed { .. }))))
    })) || matches!(
        answer,
        Ok(command_surface::Answer {
            outcome: command_surface::Outcome::Error(_),
            ..
        }) | Err(_)
    );
    let mut text = match format_answer(command, answer.as_ref()) {
        Ok(text) | Err(text) => text,
    };
    if let Ok(answer) = &answer {
        for next in &answer.envelope.next {
            let access = crate::commands::command(&next.request.operation)
                .and_then(|row| {
                    row.registration().and_then(|registration| {
                        registration.tool_access(&next.request.arguments, row).ok()
                    })
                })
                .unwrap_or(ToolAccess::Read);
            let tool = Tool::with_access(access);
            text.push_str(&format!(
                "\nnext: {} {}",
                tool.name(),
                arguments_for(&next.request)
            ));
        }
    }
    Ok((text, structured, failed))
}

/// The newest version negotiated by `initialize`, and the one offered to a
/// client that asks for a version this server does not know.
const INITIALIZE_FALLBACK: &str = "2025-11-25";

/// The first version whose requests carry the protocol version and client
/// capabilities in each request's `_meta` instead of an `initialize`.
const REQUEST_METADATA_FROM: &str = "2026-07-28";

const VERSIONS: &[&str] = &[
    "2024-11-05",
    "2025-03-26",
    "2025-06-18",
    INITIALIZE_FALLBACK,
    REQUEST_METADATA_FROM,
];

fn capabilities() -> Value {
    json!({"tools": {}, "completions": {}})
}

fn server_info() -> Value {
    json!({"name": "polylogue", "version": env!("CARGO_PKG_VERSION")})
}

#[derive(Default)]
struct Session {
    initialized: bool,
    request_metadata: bool,
}

enum Reply {
    Message(Value),
    Completion {
        id: Value,
        arguments: crate::protocol::complete::Arguments,
        deadline_ms: Option<i64>,
        with_result_type: bool,
    },
    Tool {
        id: Value,
        name: String,
        arguments: serde_json::Map<String, Value>,
        with_result_type: bool,
        deadline_ms: Option<i64>,
        tool_call_id: Option<String>,
    },
    None,
}

fn success(id: Value, result: Value) -> Value {
    json!({"jsonrpc": "2.0", "id": id, "result": result})
}

fn error(id: Value, code: i64, message: &str) -> Value {
    json!({"jsonrpc": "2.0", "id": id, "error": {"code": code, "message": message}})
}

impl Session {
    fn prepare(&mut self, request: Value) -> Reply {
        let id = request.get("id").cloned().unwrap_or(Value::Null);
        let valid_id = id.is_null() || id.is_string() || id.is_number();
        let id = if valid_id { id } else { Value::Null };
        let invalid = |code, message| Reply::Message(error(id.clone(), code, message));
        let Some(method) = request["method"].as_str() else {
            // Client responses to server requests have no method.
            return if request.get("result").is_some() || request.get("error").is_some() {
                Reply::None
            } else {
                invalid(-32600, "Invalid request")
            };
        };
        if request["jsonrpc"] != "2.0" || !valid_id {
            return invalid(-32600, "Invalid request");
        }
        if request.get("id").is_none() {
            return Reply::None;
        }
        let params = request.get("params").cloned().unwrap_or_else(|| json!({}));
        if !params.is_object() {
            return invalid(-32602, "Invalid params");
        }
        if method == "initialize" {
            let Some(version) = params["protocolVersion"].as_str() else {
                return invalid(-32602, "protocolVersion is required");
            };
            if !params["capabilities"].is_object()
                || !params["clientInfo"]["name"].is_string()
                || !params["clientInfo"]["version"].is_string()
            {
                return invalid(-32602, "clientInfo and capabilities are required");
            }
            let version = if VERSIONS.contains(&version) && version != REQUEST_METADATA_FROM {
                version
            } else {
                INITIALIZE_FALLBACK
            };
            self.initialized = true;
            return Reply::Message(success(
                id,
                json!({
                    "protocolVersion": version, "capabilities": capabilities(),
                    "serverInfo": server_info(),
                    "instructions": crate::manual::card(),
                }),
            ));
        }
        let meta = &params["_meta"];
        let version = meta["io.modelcontextprotocol/protocolVersion"].as_str();
        if method == "ping"
            && !self.request_metadata
            && (!self.initialized || version.is_none_or(|version| version < REQUEST_METADATA_FROM))
        {
            return Reply::Message(success(id, json!({})));
        }
        let with_result_type =
            self.request_metadata || version.is_some_and(|v| v >= REQUEST_METADATA_FROM);
        if !self.initialized || with_result_type || method == "server/discover" {
            let mut missing = Vec::new();
            if version.is_none() {
                missing.push("io.modelcontextprotocol/protocolVersion");
            }
            if !meta["io.modelcontextprotocol/clientCapabilities"].is_object() {
                missing.push("io.modelcontextprotocol/clientCapabilities");
            }
            if !missing.is_empty() {
                return invalid(
                    -32602,
                    &format!(
                        "request _meta is missing or has malformed required fields: {}",
                        missing.join(", ")
                    ),
                );
            }
            if !VERSIONS.contains(&version.unwrap()) {
                let mut reply = error(id, -32022, "Unsupported protocol version");
                reply["error"]["data"] = json!({"requested":version, "supported":VERSIONS});
                return Reply::Message(reply);
            }
            if method != "server/discover" && !self.initialized {
                self.request_metadata = true;
            }
        }
        if method == "server/discover" {
            return Reply::Message(success(
                id,
                json!({
                    "resultType": "complete", "supportedVersions": VERSIONS,
                    "capabilities": capabilities(), "instructions": crate::manual::card(),
                    "ttlMs": 0, "cacheScope": "private",
                    "_meta": {"io.modelcontextprotocol/serverInfo": server_info()},
                }),
            ));
        }
        let with_result_type = self.request_metadata || with_result_type;
        match method {
            "completion/complete" => match completion::arguments(&params) {
                Ok(arguments) => Reply::Completion {
                    id,
                    arguments,
                    deadline_ms: meta["deadline_ms"].as_i64(),
                    with_result_type,
                },
                Err(message) => invalid(-32602, message),
            },
            "tools/list" => {
                let mut result = json!({"tools": tools()});
                if with_result_type {
                    result["resultType"] = json!("complete");
                }
                Reply::Message(success(id, result))
            }
            "tools/call" => {
                let Some(name) = params["name"].as_str() else {
                    return invalid(-32602, "tool name is required");
                };
                let arguments = match params.get("arguments") {
                    None | Some(Value::Null) => serde_json::Map::new(),
                    Some(Value::Object(arguments)) => arguments.clone(),
                    _ => return invalid(-32602, "tool arguments must be an object"),
                };
                Reply::Tool {
                    id,
                    name: name.to_owned(),
                    arguments,
                    with_result_type,
                    deadline_ms: meta["deadline_ms"].as_i64(),
                    tool_call_id: meta["claudecode/toolUseId"].as_str().map(str::to_owned),
                }
            }
            _ => invalid(-32601, "Method not found"),
        }
    }
}

impl Reply {
    fn answer(self, archive: &Archive) -> Option<Value> {
        self.answer_with_limit(archive, &tokio_util::sync::CancellationToken::new())
    }

    fn answer_with_limit(
        self,
        archive: &Archive,
        cancelled: &tokio_util::sync::CancellationToken,
    ) -> Option<Value> {
        match self {
            Self::None => None,
            Self::Message(message) => Some(message),
            Self::Completion {
                id,
                arguments,
                deadline_ms,
                with_result_type,
            } => Some(completion::answer(
                id,
                archive,
                arguments,
                deadline_ms,
                cancelled,
                with_result_type,
            )),
            Self::Tool {
                id,
                name,
                arguments,
                with_result_type,
                deadline_ms,
                tool_call_id,
            } => {
                let (text, structured, failed) = match call_with_limit(
                    archive,
                    &name,
                    arguments,
                    deadline_ms,
                    cancelled,
                    tool_call_id,
                ) {
                    Ok(answer) => answer,
                    Err(text) => {
                        let answer =
                            command_surface::Answer::<Value>::error(crate::protocol::failure(
                                polylogue_model::Code::BadRequest,
                                text.clone(),
                            ));
                        (
                            text,
                            serde_json::to_value(answer).expect("failure serializes"),
                            true,
                        )
                    }
                };
                let mut result = json!({"content": [{"type": "text", "text": text}], "structuredContent": structured, "isError": failed});
                if with_result_type {
                    result["resultType"] = json!("complete");
                }
                Some(success(id, result))
            }
        }
    }
}

type Worker<'scope> = (
    Value,
    tokio_util::sync::CancellationToken,
    std::thread::ScopedJoinHandle<'scope, io::Result<()>>,
);

fn serve(input: impl BufRead, output: impl Write + Send, archive: &Archive) -> io::Result<()> {
    let output = std::sync::Mutex::new(output);
    let write = |message: Value| -> io::Result<()> {
        let mut output = output
            .lock()
            .map_err(|_| io::Error::other("MCP output lock failed"))?;
        serde_json::to_writer(&mut *output, &message)?;
        output.write_all(b"\n")?;
        output.flush()
    };
    std::thread::scope(|scope| {
        let mut session = Session::default();
        let mut workers: Vec<Worker<'_>> = Vec::new();
        let result = (|| {
            for line in input.lines() {
                let mut index = 0;
                while index < workers.len() {
                    if workers[index].2.is_finished() {
                        workers
                            .swap_remove(index)
                            .2
                            .join()
                            .map_err(|_| io::Error::other("MCP tool thread failed"))??;
                    } else {
                        index += 1;
                    }
                }
                let line = line?;
                if line.trim().is_empty() {
                    continue;
                }
                let reply = match serde_json::from_str::<Value>(&line) {
                    Ok(request) => {
                        if request["method"] == "notifications/cancelled"
                            && request.get("id").is_none()
                        {
                            for (id, cancelled, _) in &workers {
                                if id == &request["params"]["requestId"] {
                                    cancelled.cancel();
                                }
                            }
                            continue;
                        }
                        session.prepare(request)
                    }
                    Err(_) => Reply::Message(error(Value::Null, -32700, "Parse error")),
                };
                if let Reply::Tool { ref id, .. } | Reply::Completion { ref id, .. } = reply {
                    let id = id.clone();
                    let cancelled = tokio_util::sync::CancellationToken::new();
                    let worker_cancelled = cancelled.clone();
                    let write = &write;
                    let worker = scope.spawn(move || {
                        if let Some(message) = reply.answer_with_limit(archive, &worker_cancelled) {
                            write(message)?;
                        }
                        Ok(())
                    });
                    workers.push((id, cancelled, worker));
                } else if let Some(message) = reply.answer(archive) {
                    write(message)?;
                }
            }
            Ok(())
        })();
        for (_, cancelled, _) in &workers {
            cancelled.cancel();
        }
        for (_, _, worker) in workers {
            worker
                .join()
                .map_err(|_| io::Error::other("MCP tool thread failed"))??;
        }
        result
    })
}

pub fn serve_stdio(archive: &Archive) -> io::Result<()> {
    serve(io::stdin().lock(), io::stdout(), archive)
}

