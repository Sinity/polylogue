use super::*;

fn probe(hosted: bool, hooks: bool, permission_hook: bool, headless_resume: bool) -> Probe {
    Probe {
        harness: "claude-code".into(),
        hosted,
        hooks,
        permission_hook,
        headless_resume,
    }
}

/// The channel is a function of the act, the state and the probe; an
/// unconfirmed mechanism is refused naming the harness, never replaced by
/// another channel.
#[test]
fn the_channel_is_a_function_of_act_state_and_probe() {
    use LiveState::*;
    let observed = probe(false, true, true, true);
    let hosted = probe(true, true, true, true);
    let bare = probe(false, false, false, false);
    let ping = Act::Ping { live: false };
    let live_ping = Act::Ping { live: true };
    for state in [Working, Waiting, Idle, Unknown] {
        assert_eq!(channel(ping, state, &observed), Ok(Channel::Hook));
        assert_eq!(channel(ping, state, &hosted), Ok(Channel::Protocol));
        assert_eq!(channel(Act::Answer, state, &observed), Ok(Channel::Hook));
        assert_eq!(
            channel(Act::Interrupt, state, &observed)
                .unwrap_err()
                .reason,
            "unsupported"
        );
        assert_eq!(
            channel(Act::Interrupt, state, &hosted),
            Ok(Channel::Protocol)
        );
        assert_eq!(
            channel(Act::Resume, state, &observed).unwrap_err().reason,
            "session_running"
        );
    }
    for state in [Ended, Stale] {
        assert_eq!(channel(ping, state, &observed), Ok(Channel::Resume));
        assert_eq!(channel(Act::Resume, state, &observed), Ok(Channel::Resume));
        assert_eq!(
            channel(live_ping, state, &observed).unwrap_err().reason,
            "session_not_live"
        );
        let refused = channel(ping, state, &bare).unwrap_err();
        assert_eq!(refused.reason, "unsupported");
        assert!(refused.detail.contains("claude-code"));
    }
    // The same inputs always give the same answer.
    assert_eq!(
        channel(ping, Working, &observed),
        channel(ping, Working, &observed)
    );
    assert_eq!(
        channel(Act::Answer, Working, &bare).unwrap_err().reason,
        "unsupported"
    );
}

/// A notice reaches running sessions only: to a session that ended or is
/// stale it is refused, whatever the harness offers, and never resumes it.
#[test]
fn a_notice_never_starts_or_resumes_a_session() {
    use LiveState::*;
    let everything = probe(true, true, true, true);
    let observed = probe(false, true, true, true);
    for state in [Ended, Stale] {
        for probe in [&everything, &observed] {
            let refused = channel(Act::Notice, state, probe).unwrap_err();
            assert_eq!(refused.reason, "session_not_live");
        }
    }
    for state in [Working, Waiting, Idle, Unknown] {
        assert_eq!(channel(Act::Notice, state, &observed), Ok(Channel::Hook));
        assert_eq!(
            channel(Act::Notice, state, &everything),
            Ok(Channel::Protocol)
        );
    }
}

/// Each harness Polylogue starts names its control protocol; any other
/// name is refused as unsupported.
#[test]
fn new_sessions_start_on_the_declared_control_protocol() {
    assert_eq!(host_channel("codex"), Ok(HostProtocol::CodexAppServer));
    assert_eq!(
        host_channel("claude-code"),
        Ok(HostProtocol::ClaudeStreamJson)
    );
    assert_eq!(host_channel("gemini-cli"), Ok(HostProtocol::Acp));
    assert_eq!(host_channel("hermes"), Ok(HostProtocol::Acp));
    let refused = host_channel("chatgpt").unwrap_err();
    assert_eq!(refused.reason, "unsupported");
    assert!(refused.detail.contains("chatgpt"));
    assert!(!HostProtocol::CodexAppServer.stdio());
    assert!(HostProtocol::Acp.stdio() && HostProtocol::ClaudeStreamJson.stdio());
}

/// The docs' channel table is the table generated from the declarations.
#[test]
fn the_docs_channel_table_equals_the_declarations() {
    let docs = include_str!("../../../../../docs/agents.md");
    let start =
        "<!-- channel table: generated by polylogue_model::live::channel::channel_table -->\n";
    let end = "<!-- end of channel table -->";
    let from = docs.find(start).expect("the docs carry the channel table") + start.len();
    let to = from + docs[from..].find(end).expect("the table's end marker");
    assert_eq!(&docs[from..to], channel_table());
    // Every declared harness has a row, hosted rows for each protocol.
    for harness in HARNESSES {
        assert!(channel_table().contains(&format!("| {} | observed |", harness.name)));
    }
    assert!(channel_table().contains("| codex | hosted (codex_app_server) | protocol |"));
}
