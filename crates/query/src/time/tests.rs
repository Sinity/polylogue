use super::*;

#[test]
fn money_literal_is_exact() {
    for (text, expected) in [
        ("12345678.123456789", Some(12_345_678_123_456_789)),
        ("$2.90", Some(2_900_000_000)),
        ("2.90USD", Some(2_900_000_000)),
        (" +2.9e0usd ", Some(2_900_000_000)),
        ("9007199.254740993", Some(9_007_199_254_740_993)),
        ("9223372036.854775807", Some(i64::MAX)),
        ("-9223372036.854775808", Some(i64::MIN)),
        ("9223372036.8547758075", None),
        ("0.0000000005", Some(1)),
        ("-0.0000000005", Some(-1)),
        ("0.00000000049", Some(0)),
        ("1e300", None),
        ("1e-9999999999999999999999999", Some(0)),
        ("NaN", None),
        ("inf", None),
        ("1.2.3", None),
    ] {
        assert_eq!(money_nusd(text), expected, "{text}");
    }
}
