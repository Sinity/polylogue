use super::*;
use serde_json::json;

fn result(record: Json, item: Json) -> ToolOutcome {
    let mut blobs = Vec::new();
    match block(&record, &item, true, &mut blobs) {
        Block::ToolResult { outcome, .. } => outcome,
        other => panic!("{other:?}"),
    }
}

#[test]
fn outcome_prefers_denial_then_interruption_then_is_error() {
    let item = json!({"type":"tool_result","tool_use_id":"t","is_error":true,"content":"no"});
    assert_eq!(
        result(json!({"toolDenialKind":"permission_rule"}), item.clone()),
        ToolOutcome::Error {
            reason: Some(ErrorReason::Denied("permission_rule".into()))
        }
    );
    assert_eq!(
        result(json!({"toolUseResult":{"interrupted":true}}), item.clone()),
        ToolOutcome::Error {
            reason: Some(ErrorReason::Interrupted)
        }
    );
    assert_eq!(result(json!({}), item), ToolOutcome::Error { reason: None });
}

#[test]
fn exit_code_comes_from_the_last_line_that_states_one() {
    let item =
        json!({"type":"tool_result","is_error":true,"content":"Exit code 1\nmore\nexit code: 2"});
    assert_eq!(
        result(json!({}), item),
        ToolOutcome::Error {
            reason: Some(ErrorReason::ExitCode(2))
        }
    );
}

#[test]
fn exit_code_zero_under_an_error_flag_is_an_error() {
    let flagged = json!({"type":"tool_result","is_error":true,"content":"done"});
    assert_eq!(
        result(json!({"toolUseResult":{"exitCode":0}}), flagged),
        ToolOutcome::Error {
            reason: Some(ErrorReason::ExitCode(0))
        }
    );
    let clean = json!({"type":"tool_result","content":"done"});
    assert_eq!(
        result(json!({"toolUseResult":{"exitCode":0}}), clean),
        ToolOutcome::Ok
    );
}

#[test]
fn background_launch_and_unreadable_status_are_unknown() {
    let item = json!({"type":"tool_result","backgroundTaskId":"b1","content":"started"});
    assert_eq!(
        result(json!({}), item),
        ToolOutcome::Unknown {
            reason: UnknownReason::RunningInBackground
        }
    );
    let item = json!({"type":"tool_result","is_error":"yes"});
    assert_eq!(
        result(json!({}), item),
        ToolOutcome::Unknown {
            reason: UnknownReason::StatusFieldUnreadable
        }
    );
}

#[test]
fn tool_use_result_applies_only_to_a_sole_result() {
    let record = json!({"toolUseResult":{"interrupted":true}});
    let content = json!([
        {"type":"tool_result","tool_use_id":"a"},
        {"type":"tool_result","tool_use_id":"b"}
    ]);
    let mut blobs = Vec::new();
    let result = blocks(&record, &content, &mut blobs);
    assert_eq!(result.len(), 2);
    for b in result {
        let Block::ToolResult { outcome, data, .. } = b else {
            panic!()
        };
        assert_eq!(outcome, ToolOutcome::Ok);
        assert_eq!(data, None);
    }
}

#[test]
fn inline_images_become_blobs() {
    let data = base64::engine::general_purpose::STANDARD.encode(b"\x89PNG fake");
    let content =
        json!([{"type":"image","source":{"type":"base64","media_type":"image/png","data":data}}]);
    let mut blobs = Vec::new();
    let b = blocks(&json!({}), &content, &mut blobs);
    assert_eq!(blobs.len(), 1);
    let Block::Image(a) = &b[0] else { panic!() };
    assert_eq!(a.blob, Some(BlobHash::of(b"\x89PNG fake")));
    assert_eq!(a.size, Some(9));
}

#[test]
fn prompt_kinds() {
    let r = json!({});
    assert_eq!(prompt_kind(&r, &json!("fix the build")), PromptKind::Prose);
    assert_eq!(prompt_kind(&r, &json!("/model opus")), PromptKind::Command);
    assert_eq!(
        prompt_kind(&r, &json!("/usr/bin/env is weird\nsee")),
        PromptKind::Prose
    );
    assert_eq!(
        prompt_kind(&r, &json!("<command-name>/clear</command-name>")),
        PromptKind::Command
    );
    assert_eq!(
        prompt_kind(&r, &json!("[Request interrupted by user]")),
        PromptKind::Harness
    );
    assert_eq!(
        prompt_kind(&r, &json!([{"type":"tool_result","tool_use_id":"t"}])),
        PromptKind::Harness
    );
    assert_eq!(
        prompt_kind(&json!({"isMeta":true}), &json!("hi")),
        PromptKind::Harness
    );
}

#[test]
fn harness_prefixes_do_not_become_authored_titles() {
    for text in [
        "[SUGGESTION MODE: Suggest what the user might naturally type next into Claude Code. Fix the parser.",
        "Caveat: The messages below are were generated by the user while running local commands.",
    ] {
        assert_eq!(prompt_kind(&json!({}), &json!(text)), PromptKind::Harness);
    }
    assert_eq!(
        prompt_kind(
            &json!({"isMeta":true}),
            &json!("Base directory for this skill: /synthetic/skill")
        ),
        PromptKind::InjectedContext
    );
    assert_eq!(
        prompt_kind(
            &json!({}),
            &json!(
                "This session is being continued from a previous session that ran out of context."
            )
        ),
        PromptKind::CompactionSummary
    );
    assert_eq!(
        prompt_kind(&json!({}), &json!("Fix the parser")),
        PromptKind::Prose
    );
}

#[test]
fn server_tool_results_pair_and_keep_structured_success_or_failure() {
    let record = serde_json::json!({"message":{"content":[
        {"type":"server_tool_use","id":"code","name":"code_execution","input":{"code":"raise RuntimeError()"}},
        {"type":"code_execution_tool_result","tool_use_id":"code","content":{"type":"code_execution_result","stdout":"before","stderr":"failed","return_code":7,"content":[{"type":"code_execution_output","file_id":"file-synthetic"}]}},
        {"type":"web_search_tool_result","tool_use_id":"search","content":{"type":"web_search_tool_result_error","error_code":"max_uses_exceeded"}}
    ]}});
    let result = blocks(&record, &record["message"]["content"], &mut Vec::new());
    let Block::ToolResult {
        call_id,
        outcome,
        output,
        data,
        ..
    } = &result[1]
    else {
        panic!("code result")
    };
    assert_eq!(call_id.as_deref(), Some("code"));
    assert_eq!(
        *outcome,
        ToolOutcome::Error {
            reason: Some(ErrorReason::ExitCode(7))
        }
    );
    assert_eq!(output.as_deref(), Some("before\nfailed"));
    assert_eq!(
        data.as_ref().unwrap()["content"],
        record["message"]["content"][1]["content"]
    );
    let Block::ToolResult {
        call_id,
        outcome,
        output,
        data,
        attachments,
        reported_duration_ms,
    } = &result[2]
    else {
        panic!("search result")
    };
    assert_eq!(call_id.as_deref(), Some("search"));
    assert_eq!(*outcome, ToolOutcome::Error { reason: None });
    assert_eq!(*output, None);
    assert_eq!(
        *data,
        Some(json!({
            "toolUseResult": null,
            "content": {"type": "web_search_tool_result_error", "error_code": "max_uses_exceeded"}
        }))
    );
    assert!(attachments.is_empty());
    assert_eq!(*reported_duration_ms, None);
}

#[test]
fn file_tool_bodies_keep_new_text_and_original_arguments() {
    for (tool, input, expected) in [
        (
            "Write",
            json!({"file_path":"/synthetic.txt","content":" Ω\n"}),
            Some(" Ω\n"),
        ),
        (
            "Edit",
            json!({"old_string":"old","new_string":"new λ"}),
            Some("new λ"),
        ),
        (
            "Read",
            json!({"file_path":"/synthetic.txt","content":"not written"}),
            None,
        ),
        (
            "MultiEdit",
            json!({"edits":[{"new_string":"a"},{"old_string":"x"},{"new_string":"b"}]}),
            Some("a\n\nb"),
        ),
        ("MultiEdit", json!({"edits":[{"old_string":"x"}]}), None),
        (
            "NotebookEdit",
            json!({"notebook_path":"/synthetic.ipynb","new_source":"print(1)"}),
            Some("print(1)"),
        ),
    ] {
        let item = json!({"type":"tool_use","name":tool,"input":input});
        let result = block(&Json::Null, &item, false, &mut Vec::new());
        let Block::ToolCall {
            input: found,
            written_text,
            ..
        } = result
        else {
            panic!("not a call")
        };
        assert_eq!(found, input);
        assert_eq!(written_text.as_deref(), expected);
    }
}

