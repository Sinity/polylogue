def test_render_outputs_rejects_an_unregistered_doc(tmp_path: Path) -> None:
    docs_root = tmp_path / "docs"
    docs_root.mkdir()
    (docs_root / "new-guide.md").write_text("# New guide\n", encoding="utf-8")
    readme_path = tmp_path / "README.md"
    readme_path.write_text(
        "<!-- BEGIN GENERATED: docs-surface -->\nold\n<!-- END GENERATED: docs-surface -->\n",
        encoding="utf-8",
    )

    with pytest.raises(ValueError, match="unindexed documentation: docs/new-guide.md"):
        render_docs_surface.render_outputs(
            readme_path=readme_path,
            docs_readme_path=docs_root / "README.md",
        )


def test_documentation_index_makes_linked_children_reachable(tmp_path: Path) -> None:
    docs_root = tmp_path / "docs"
    records = docs_root / "records"
    records.mkdir(parents=True)
    index = records / "README.md"
    index.write_text("# Records\n\n- [Incident](incident.md)\n", encoding="utf-8")
    (records / "incident.md").write_text("# Incident\n", encoding="utf-8")
    entries = (DocsEntry("Records", "docs/records/README.md", "Investigation records.", "archive"),)

    assert render_docs_surface.undocumented_paths(entries, docs_root=docs_root) == set()


def test_render_outputs_rejects_duplicate_document_registration(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    docs_root = tmp_path / "docs"
    docs_root.mkdir()
    (docs_root / "guide.md").write_text("# Guide\n", encoding="utf-8")
    readme_path = tmp_path / "README.md"
    readme_path.write_text(
        "<!-- BEGIN GENERATED: docs-surface -->\nold\n<!-- END GENERATED: docs-surface -->\n",
        encoding="utf-8",
    )
    duplicate_entries = (
        DocsEntry("Guide", "docs/guide.md", "First registration.", "guide"),
        DocsEntry("Guide again", "docs/guide.md", "Duplicate registration.", "reference"),
    )
    monkeypatch.setattr(render_docs_surface, "DOCS_REFERENCE_ENTRIES", duplicate_entries)

    with pytest.raises(ValueError, match="duplicate documentation entries: docs/guide.md"):
        render_docs_surface.render_outputs(
            readme_path=readme_path,
            docs_readme_path=docs_root / "README.md",
        )


